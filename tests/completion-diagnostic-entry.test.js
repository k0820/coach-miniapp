const assert = require('assert')
const fs = require('fs')
const path = require('path')
const { classifyCompletion, route } = require('../cloudfunctions/diagnoseCoachCompletion/service')
const root = path.join(__dirname, '..')
const page = fs.readFileSync(path.join(root, 'pages/session/session.js'), 'utf8')
const cloud = fs.readFileSync(path.join(root, 'cloudfunctions/diagnoseCoachCompletion/index.js'), 'utf8')

assert.match(page, /name:\s*'diagnoseCoachCompletion'/)
assert.match(page, /action:\s*'diagnose'/)
assert.match(cloud, /return route\(event,/)
assert.doesNotMatch(cloud, /db\.collection[\s\S]*?\.(add|set|update|remove)\(/)
assert.deepStrictEqual(route({ action: 'bad', bookingId: 'b1' }, () => ({})), { ok: false, code: 'INVALID_ACTION' })
assert.deepStrictEqual(route({ action: 'diagnose' }, () => ({})), { ok: false, code: 'INVALID_BOOKING_ID' })
assert.strictEqual(classifyCompletion({ receipts: [], booking: { status: 'booked' }, incomes: [] }).state, 'A_BOTH_COMMANDS_NOT_SUCCEEDED')
assert.strictEqual(classifyCompletion({ receipts: [{ command: 'updateBookingContent', status: 'succeeded' }], booking: { status: 'booked' }, incomes: [] }).state, 'C_CONTENT_SUCCEEDED_COMPLETE_NOT_SUCCEEDED')
assert.strictEqual(classifyCompletion({ receipts: [{ command: 'updateBookingContent', status: 'succeeded' }, { command: 'completeBooking', status: 'succeeded' }], booking: { status: 'done' }, incomes: [{ id: 'i1' }] }).state, 'B_BOTH_COMMANDS_SUCCEEDED')
assert.strictEqual(classifyCompletion({ receipts: [{ command: 'completeBooking', status: 'succeeded' }], booking: { status: 'done' }, incomes: [] }).strict, false)
assert.strictEqual(classifyCompletion({ receipts: [{ command: 'completeBooking', status: 'processing' }], booking: { status: 'booked' }, incomes: [] }).state, 'COMMAND_RESULT_PENDING')
process.stdout.write('completion diagnostic entry tests: PASS (page→dedicated read-only router, strict A/B/C, anomalous state)\n')
