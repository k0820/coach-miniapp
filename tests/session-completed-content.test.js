const assert = require('assert')
const fs = require('fs')
const path = require('path')
const { completedViewState } = require('../utils/session-view')
const verified = { bookingId: 'b1', status: 'done', packageId: 'p1', items: [{ name: '高位下拉', sets: 4, reps: 12, weight: 30 }], notes: '保持肩胛稳定', category: '背部训练', duration: 60, summary: '历史总结' }
const state = completedViewState({ booking: { id: 'b1', date: '2026-09-16' }, items: [] }, verified)
assert.equal(state.done, true)
assert.deepStrictEqual(state.items, verified.items)
assert.equal(state.notes, verified.notes)
assert.equal(state.category, verified.category)
assert.equal(state.duration, verified.duration)
const root = path.join(__dirname, '..'), page = fs.readFileSync(path.join(root, 'pages/session/session.js'), 'utf8'), view = fs.readFileSync(path.join(root, 'pages/session/session.wxml'), 'utf8')
assert.match(page, /completedViewState\(this\.data,result\.after\.booking\)/)
assert.match(view, /class="history-values"/)
assert.match(view, /class="notes history-notes"/)
assert.doesNotMatch(page, /completedViewState[\s\S]{0,200}(saveDB|runCommand)/)
process.stdout.write('session completed content tests: PASS (verified cloud content retained and rendered read-only)\n')
