const assert=require('assert')
const fs=require('fs')
const {createWorld,loadExercisePicker,settle}=require('./helpers/local-first-world')
async function run(){
  const world=createWorld();world.online=false
  world.seed({students:[],bookings:[],incomes:[],sales:[],settings:{},customExercises:[{id:'custom-back',name:'测试背部动作',group:'背'}]})
  const picker=loadExercisePicker();picker.refresh()
  assert.ok(!picker.data.groups.includes('全部'))
  assert.equal(picker.data.sections.length,1)
  picker.chooseGroup({currentTarget:{dataset:{group:'背'}}})
  assert.deepStrictEqual(picker.data.sections.map(x=>x.group),['背'])
  assert.equal(picker.data.customGroup,'背')
  const exercise=picker.data.sections[0].items.find(x=>x.isCustom)
  let menu
  wx.showModal=options=>world.counters.modals.push(options)
  wx.showActionSheet=options=>{menu=options}
  picker.manageCustom({currentTarget:{dataset:{item:exercise}}})
  assert.deepStrictEqual(menu.itemList,['编辑动作','删除动作'])
  menu.success({tapIndex:0})
  assert.equal(picker.data.customValue,exercise.name)
  picker.manageCustom({currentTarget:{dataset:{item:exercise}}});menu.success({tapIndex:1})
  const confirm=world.counters.modals.at(-1)
  assert.equal(confirm.title,'删除自定义动作')
  assert.equal(world.localDB().customExercises.length,1,'确认前不能删除')
  confirm.success({confirm:false});assert.equal(world.localDB().customExercises.length,1)
  await confirm.success({confirm:true});await settle(5)
  assert.equal(world.localDB().customExercises.length,0)
  picker.refresh()
  const builtin=picker.data.sections[0].items.find(x=>!x.isCustom)
  picker.manageCustom({currentTarget:{dataset:{item:builtin}}})
  assert.deepStrictEqual(menu.itemList,['编辑动作','删除动作'],'系统自带动作也必须有完整长按菜单')
  menu.success({tapIndex:0})
  assert.equal(picker.data.editingBuiltinKey,builtin.builtinKey,'系统动作必须可以进入编辑状态')
  picker.cancelEdit()
  picker.manageCustom({currentTarget:{dataset:{item:builtin}}});menu.success({tapIndex:1})
  const builtinConfirm=world.counters.modals.at(-1)
  await builtinConfirm.success({confirm:true});await settle(5)
  assert.ok(world.localDB().customExercises.some(x=>x.builtinKey===builtin.builtinKey&&x.hidden),'删除系统动作应持久记录为隐藏，同时不改历史课程')
  picker.refresh()
  assert.ok(!picker.data.sections[0].items.some(x=>x.builtinKey===builtin.builtinKey),'被删除的系统动作不应继续显示')
  const wxml=fs.readFileSync(require.resolve('../components/exercise-picker/exercise-picker.wxml'),'utf8')
  const wxss=fs.readFileSync(require.resolve('../components/exercise-picker/exercise-picker.wxss'),'utf8')
  const sessionWxml=fs.readFileSync(require.resolve('../pages/session/session.wxml'),'utf8')
  const sessionWxss=fs.readFileSync(require.resolve('../pages/session/session.wxss'),'utf8')
  assert.ok(wxml.includes('bindlongpress="manageCustom"'))
  assert.ok(!wxml.includes('catchtap="deleteCustom"'))
  assert.ok(!wxml.includes('catchtap="startEdit"'))
  assert.ok(wxml.includes('class="exercise-card'), '动作库必须使用清楚的卡片入口')
  assert.ok(/\.flow\{[^}]*display:grid[^}]*grid-template-columns:repeat\(3,minmax\(0,1fr\)\)/.test(wxss), '动作选择必须是更省空间的三列排版')
  const compactCard=/\.exercise-card\{([^}]*)\}/.exec(wxss)
  const compactHeight=compactCard&&/min-height:([\d.]+)rpx/.exec(compactCard[1])
  assert.ok(compactHeight&&Number(compactHeight[1])>=54&&Number(compactHeight[1])<=64, '动作按钮高度必须保持在 54–64rpx，避免卡片过大')
  assert.ok(compactCard&&!/box-shadow/.test(compactCard[1]), '动作按钮必须使用轻量扁平样式，不能再叠卡片阴影')
  assert.ok(!wxml.includes('点选添加'), '紧凑动作按钮不重复显示「点选添加」说明')
  assert.ok(sessionWxml.includes('class="exercise-fields"'), '已选动作的组数、次数和重量必须放进独立参数区')
  assert.ok(/\.exercise-fields\{[^}]*display:grid[^}]*grid-template-columns:repeat\(3,1fr\)/.test(sessionWxss), '三个训练参数必须等宽排列，不能和名称挤成一行')
  const selectedCards=[...sessionWxss.matchAll(/\.exercise-row\{([^}]*)\}/g)]
  const selectedCard=selectedCards.at(-1)
  const selectedPadding=selectedCard&&/padding:([\d.]+)rpx/.exec(selectedCard[1])
  assert.ok(selectedPadding&&Number(selectedPadding[1])<=8, '本节课的已选动作卡片必须再次压缩留白，减少纵向滑动')
  const metricFields=[...sessionWxss.matchAll(/\.metric-field\{([^}]*)\}/g)]
  const metricField=metricFields.at(-1)
  const metricHeight=metricField&&/height:([\d.]+)rpx/.exec(metricField[1])
  assert.ok(metricHeight&&Number(metricHeight[1])<=44, '组数、次数、重量输入框必须保持紧凑')
  assert.ok(sessionWxml.includes('class="card training-content-card"'), '本节课内容外层必须使用紧凑容器，不能继续沿用默认大卡片留白')
  world.restoreUi()
  console.log('exercise picker categories: PASS (compact three-column buttons, dense selected cards, long press, confirm before delete)')
}
run().catch(error=>{console.error(error);process.exitCode=1})
